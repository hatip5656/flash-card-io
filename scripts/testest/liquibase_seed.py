"""Write the Liquibase changesets that seed the TESTEST exams and writing/speaking tasks.
Usage: python3 -I liquibase_seed.py <convert-out-dir> <changelog-dir>
Reads testest-exams.json and testest-tasks.json (convert.py output) and writes 028-testest-exams.sql and
029-testest-tasks.sql. One changeset per row with runOnChange, so regenerating after a correction
re-applies just the rows that changed. Media is not seeded here (binary; see import_testest.py)."""
import json, os, sys

src, dest = sys.argv[1:3]
TAG = '$tt$'


def q(v):
    """SQL literal: NULL, a number, or a dollar-quoted string (JSON and Estonian text need no escaping)."""
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'TRUE' if v else 'FALSE'
    if isinstance(v, (int, float)): return str(v)
    s = v if isinstance(v, str) else json.dumps(v, ensure_ascii=False, separators=(',', ':'))
    if TAG in s or '${' in s:
        raise ValueError('value contains the quote tag or a Liquibase placeholder: ' + s[:80])
    return f'{TAG}{s}{TAG}'


def changeset(author_id, sql):
    return (f'--changeset testest:{author_id} runOnChange:true splitStatements:false stripComments:false\n'
            f'{sql}\n\n')


def write(name, header, sets):
    with open(os.path.join(dest, name), 'w') as f:
        f.write('--liquibase formatted sql\n\n')
        f.write(f'-- Generated by scripts/testest/liquibase_seed.py from the TESTEST scrape. {header}\n\n')
        for cid, sql in sets:
            f.write(changeset(cid, sql))
    print(name, len(sets), 'changesets')


exams = json.load(open(os.path.join(src, 'testest-exams.json')))
write('028-testest-exams.sql', 'Placement, diagnostic and sample tests.', [(
    'exam-' + e['id'],
    'INSERT INTO official_exams (id, cefr_level, title, title_tr, title_en, source, questions, kind, skill, '
    'variant, sort_order, scoring, time_limit_minutes)\n'
    f"VALUES ({q(e['id'])}, {q(e['level'])}, {q(e['title'])}, {q(e['titleTr'])}, {q(e['titleEn'])}, "
    f"{q(e['source'])}, {q(e['questions'])}::jsonb, {q(e['kind'])}, {q(e['skill'])}, {q(e['variant'])}, "
    f"{q(e['sortOrder'])}, {q(e['scoring'])}::jsonb, {q(e['timeLimitMinutes'])})\n"
    'ON CONFLICT (id) DO UPDATE SET cefr_level = EXCLUDED.cefr_level, title = EXCLUDED.title, '
    'title_tr = EXCLUDED.title_tr, title_en = EXCLUDED.title_en, source = EXCLUDED.source, '
    'questions = EXCLUDED.questions, kind = EXCLUDED.kind, skill = EXCLUDED.skill, variant = EXCLUDED.variant, '
    'sort_order = EXCLUDED.sort_order, scoring = EXCLUDED.scoring, time_limit_minutes = EXCLUDED.time_limit_minutes;'
) for e in exams])

tasks = json.load(open(os.path.join(src, 'testest-tasks.json')))
write('029-testest-tasks.sql', 'Writing and speaking tasks with model answers.', [(
    'task-' + t['id'],
    'INSERT INTO exam_tasks (id, kind, skill, cefr_level, variant, title, title_tr, title_en, source, sort_order, '
    'time_limit_minutes, intro, tasks)\n'
    f"VALUES ({q(t['id'])}, {q(t['kind'])}, {q(t['skill'])}, {q(t['level'])}, {q(t['variant'])}, {q(t['title'])}, "
    f"{q(t['titleTr'])}, {q(t['titleEn'])}, {q(t['source'])}, {q(t['sortOrder'])}, {q(t['timeLimitMinutes'])}, "
    f"{q(t['intro'])}, {q(t['tasks'])}::jsonb)\n"
    'ON CONFLICT (id) DO UPDATE SET kind = EXCLUDED.kind, skill = EXCLUDED.skill, cefr_level = EXCLUDED.cefr_level, '
    'variant = EXCLUDED.variant, title = EXCLUDED.title, title_tr = EXCLUDED.title_tr, title_en = EXCLUDED.title_en, '
    'source = EXCLUDED.source, sort_order = EXCLUDED.sort_order, time_limit_minutes = EXCLUDED.time_limit_minutes, '
    'intro = EXCLUDED.intro, tasks = EXCLUDED.tasks;'
) for t in tasks])
